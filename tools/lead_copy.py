def apply_replacements(text: str) -> str:
    normalized = text
    for source, replacement in REPLACEMENTS:
        normalized = normalized.replace(source, replacement)
    return normalized


def normalize_lead_copy(destination: Path, errors: list[str]) -> None:
    targets = sorted([*destination.rglob("*.html"), *destination.rglob("*.js")])
    for path in targets:
        text = path.read_text(encoding="utf-8")
        normalized = apply_replacements(text)
        if normalized != text:
            path.write_text(normalized, encoding="utf-8")

        relative = path.relative_to(destination).as_posix()
        for marker in FORBIDDEN_MARKERS:
            if marker in normalized:
                errors.append(f"{relative}: unconditional lead or photo-handoff claim remains: {marker}")


def self_test() -> int:
    failures: list[str] = []
    with tempfile.TemporaryDirectory(prefix="parket36-lead-copy-") as temp:
        destination = Path(temp) / "_site"
        (destination / "js").mkdir(parents=True)
        html = destination / "index.html"
        script = destination / "js" / "main.js"
        html.write_text(
            "<p>Форма отправит заявку Ивану через защищённую форму и скопирует готовый текст. Его удобно использовать, чтобы приложить фотографии пола отдельными сообщениями или продиктовать детали по телефону.</p>"
            "<p>Заявка отправляется Ивану через защищённую форму. Нажимая кнопку, вы соглашаетесь с правилами.</p>"
            "<p>Заполните короткую форму: заявка уйдёт Ивану, а готовый текст скопируется, чтобы вы могли приложить фотографии пола отдельными сообщениями.</p>",
            encoding="utf-8",
        )
        script.write_text(
            "const disclosure = 'Заявка отправляется Ивану через защищённую форму. Готовый текст также копируется, чтобы вы могли отправить фото отдельными сообщениями.';\n"
            "const status = 'Заявка отправлена Ивану. Текст также скопирован — приложите к нему фотографии пола.';\n"
            "const guard = next.startsWith('Заявка отправлена Ивану');\n"
            "const errorPrefix = 'Автоматически отправить заявку не удалось.';\n"
            "const summary = 'Данных достаточно для первого ориентира. Фотографии и видео всё равно отправляются отдельными сообщениями.';",
            encoding="utf-8",
        )

        errors: list[str] = []
        normalize_lead_copy(destination, errors)
        if errors:
            failures.extend(errors)
        combined = html.read_text(encoding="utf-8") + script.read_text(encoding="utf-8")
        required = (
            "попробует сохранить",
            "уведомление Ивану не подтвердится",
            "После связи Иван подскажет, каким способом передать фотографии пола",
            "Способ передачи фото согласуйте с Иваном",
            "Заявка отправлена Ивану. Текст скопирован как памятка",
            "next.startsWith('Заявка отправлена Ивану')",
            "Автоматически отправить заявку не удалось",
            "После связи Иван подскажет, как передать фотографии и видео",
        )
        for marker in required:
            if marker not in combined:
                failures.append(f"normalized lead copy missing marker: {marker}")
        for marker in FORBIDDEN_MARKERS:
            if marker in combined:
                failures.append(f"stale unconditional claim remained: {marker}")

        second = apply_replacements(combined)
        if second != combined:
            failures.append("lead copy normalization is not idempotent")

    if failures:
        print("Lead copy self-test failed:")
        for failure in failures:
            print(f"  - {failure}")
        return 1
    print("Lead copy self-test passed")
    return 0


if __name__ == "__main__":
    sys.exit(self_test())
